"""Tests for the cargo-lock-ghsa-gap agent skill (skills/cargo-lock-ghsa-gap/).

Checks that SKILL.md is a valid skill file and that cargo_lock_ghsa_gap.py parses Cargo.lock and sorts
each advisory correctly. No network: every HTTP answer is a fixture. The openssl and russh fixtures
copy the IDs, aliases, severities and fixed versions OSV.dev served on 2026-11-10 UTC (RUSTSEC-2026-0154's
aliases are trimmed to its CVE to exercise the shared-CVE path). The Untrusted tests feed hostile text into
remote fields and check none reaches the output.
Made with AI agents working in MV2's (Munim, Inc.) name.
"""
