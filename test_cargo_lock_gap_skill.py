BATCH_ANSWER = {"results": [
    {"vulns": [{"id": "RUSTSEC-2026-0463"}, {"id": "GHSA-8c75-8mhr-p7r9"}, {"id": "GHSA-ghm9-cr32-g9qj"}]},
    {"vulns": [{"id": "GHSA-4r3c-5hpg-58qr"}, {"id": "RUSTSEC-2026-0154"}, {"id": "GHSA-g9f8-wqj9-fjw5"}]},
    {},
]}


def fake_get(url):
    return FIXTURES.get(url, (404, None))


class FakePost:
    def __init__(self, answer=BATCH_ANSWER, status=200):
        self.answer, self.status, self.calls = answer, status, []

    def __call__(self, url, payload):
        self.calls.append((url, payload))
        return self.status, self.answer


def statuses(report):
    return {(r["package"], r["id"]): r["status"] for r in report["rows"]}


def run_main(args, get=fake_get, post=None):
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        code = m.main(args, get=get, post=post or FakePost())
    return code, buf.getvalue()


def write_lock(text):
    fd, path = tempfile.mkstemp(suffix=".lock")
    with os.fdopen(fd, "w", encoding="utf-8") as fh:
        fh.write(text)
    return path


class SkillFile(unittest.TestCase):
    def test_frontmatter(self):
        fields, body = frontmatter(read(SKILL_MD))
        self.assertEqual(fields["name"], "cargo-lock-ghsa-gap")
        self.assertEqual(fields["license"], "Apache-2.0")
        self.assertTrue(20 < len(fields["description"]) < 1024)
        self.assertIn("scripts/cargo_lock_ghsa_gap.py", body)

    def test_disclosure_and_no_address(self):
        text = read(SKILL_MD)
        self.assertIn("Made with AI agents", text)
        self.assertIn("MV2, Munim, Inc., mv2@munimtech.com", text)
        self.assertIsNone(STREET.search(text))
        self.assertIsNone(STREET.search(read(SCRIPT)))
        self.assertNotIn("MIT License", text)


class ParseLock(unittest.TestCase):
    def test_crates_io_only_and_deduplicated(self):
        packages, skipped = m.parse_cargo_lock(LOCK)
        self.assertEqual(packages, PACKAGES)
        self.assertEqual(skipped, 2)  # myapp (no source) and gitdep (git)

    def test_crlf_and_bad_names(self):
        text = LOCK.replace("\n", "\r\n").replace('name = "serde"', 'name = "ser de"')
        packages, skipped = m.parse_cargo_lock(text)
        self.assertEqual(packages, PACKAGES[:2])
        self.assertEqual(skipped, 3)

    def test_payload(self):
        post = FakePost()
        m.query_osv(PACKAGES, post)
        url, payload = post.calls[0]
        self.assertEqual(url, "https://api.osv.dev/v1/querybatch")
        self.assertEqual(payload["queries"][1],
                         {"package": {"ecosystem": "crates.io", "name": "russh"}, "version": "0.60.0"})


class Classify(unittest.TestCase):
    def setUp(self):
        self.report = m.run(LOCK, fake_get, FakePost())

    def test_statuses(self):
        self.assertEqual(statuses(self.report), {
            ("openssl", "RUSTSEC-2026-0463"): "RUSTSEC",
            ("openssl", "GHSA-8c75-8mhr-p7r9"): "COVERED",
            ("openssl", "GHSA-ghm9-cr32-g9qj"): "GHSA_ONLY",
            ("russh", "GHSA-4r3c-5hpg-58qr"): "GHSA_ONLY",
            ("russh", "RUSTSEC-2026-0154"): "RUSTSEC",
            ("russh", "GHSA-g9f8-wqj9-fjw5"): "COVERED",
        })
        self.assertEqual(self.report["errors"], [])
        self.assertEqual(self.report["packages_checked"], 3)

    def test_covered_names_the_rustsec_record(self):
        rows = {r["id"]: r for r in self.report["rows"]}
        self.assertEqual(rows["GHSA-8c75-8mhr-p7r9"]["rustsec"], ["RUSTSEC-2026-0463"])  # alias
        self.assertEqual(rows["GHSA-g9f8-wqj9-fjw5"]["rustsec"], ["RUSTSEC-2026-0154"])  # shared CVE
        gap = rows["GHSA-4r3c-5hpg-58qr"]
        self.assertEqual((gap["severity"], gap["cves"], gap["fixed"]), ("HIGH", ["CVE-2026-48110"], ["0.61.0"]))

    def test_render(self):
        text = m.render(self.report)
        self.assertIn("NOT in RustSec, so cargo-audit and cargo-deny will NOT report these (2):", text)
        self.assertIn("russh 0.60.0  GHSA-4r3c-5hpg-58qr  HIGH  CVE-2026-48110  fixed in 0.61.0", text)
        self.assertIn("https://github.com/advisories/GHSA-ghm9-cr32-g9qj", text)
        self.assertIn("RUSTSEC-2026-0154, RUSTSEC-2026-0463", text)
        self.assertNotIn("GHSA-8c75-8mhr-p7r9", text)

    def test_withdrawn_ghsa_is_dropped(self):
        fx = dict(FIXTURES)
        fx[OSV + "GHSA-ghm9-cr32-g9qj"] = (200, rec("GHSA-ghm9-cr32-g9qj", "openssl", ["CVE-2026-41681"],
                                                    "0.10.78", "HIGH", withdrawn="2026-11-01T00:00:00Z"))
        report = m.run(LOCK, lambda u: fx.get(u, (404, None)), FakePost())
        self.assertNotIn(("openssl", "GHSA-ghm9-cr32-g9qj"), statuses(report))


class MainExit(unittest.TestCase):
    def test_gap_exits_1(self):
        path = write_lock(LOCK)
        try:
            code, out = run_main([path])
            self.assertEqual(code, 1)
            self.assertIn("GHSA-ghm9-cr32-g9qj", out)
            code, out = run_main([path, "--json"])
            self.assertEqual(code, 1)
            self.assertEqual(len(json.loads(out)["rows"]), 6)
        finally:
            os.remove(path)

    def test_no_gap_exits_0(self):
        answer = {"results": [{"vulns": [{"id": "RUSTSEC-2026-0463"}]}, {}, {}]}
        path = write_lock(LOCK)
        try:
            code, out = run_main([path], post=FakePost(answer))
            self.assertEqual(code, 0)
            self.assertIn("No GitHub-only advisories", out)
        finally:
            os.remove(path)

    def test_network_error_exits_2(self):
        path = write_lock(LOCK)
        try:
            code, out = run_main([path], post=FakePost(None, status=0))
            self.assertEqual(code, 2)
            self.assertIn("WARNING: OSV querybatch failed", out)
        finally:
            os.remove(path)

    def test_missing_file_exits_2(self):
        buf = io.StringIO()
        with contextlib.redirect_stderr(buf):
            code, _ = run_main([os.path.join(HERE, "no-such-dir", "Cargo.lock")])
        self.assertEqual(code, 2)


class Limits(unittest.TestCase):
    def test_batches_of_1000(self):
        lines = []
        for i in range(1001):
            lines += ["[[package]]", 'name = "c%d"' % i, 'version = "1.0.0"',
                      'source = "registry+https://github.com/rust-lang/crates.io-index"', ""]
        calls = []

        def post(url, payload):
            calls.append(len(payload["queries"]))
            return 200, {"results": [{} for _ in payload["queries"]]}

        report = m.run("\n".join(lines), fake_get, post)
        self.assertEqual(calls, [1000, 1])
        self.assertEqual(report["rows"], [])

    def test_lookup_cap(self):
        old = m.MAX_LOOKUPS
        m.MAX_LOOKUPS = 2
        try:
            report = m.run(LOCK, fake_get, FakePost())
        finally:
            m.MAX_LOOKUPS = old
        st = statuses(report)
        self.assertEqual(st[("openssl", "GHSA-8c75-8mhr-p7r9")], "COVERED")
        self.assertEqual(st[("openssl", "GHSA-ghm9-cr32-g9qj")], "UNCHECKED")
        self.assertEqual(st[("russh", "GHSA-4r3c-5hpg-58qr")], "UNCHECKED")
        self.assertTrue(any("stopped after 2" in e for e in report["errors"]))


class Untrusted(unittest.TestCase):
    def test_hostile_fields_never_printed(self):
        fx = dict(FIXTURES)
        bad = rec("GHSA-ghm9-cr32-g9qj", "openssl", ["CVE-2026-41681; " + HOSTILE, HOSTILE],
                  "0.10.78 && " + HOSTILE, "HIGH " + HOSTILE,
                  refs=["https://evil.example/" + HOSTILE], summary=HOSTILE)
        fx[OSV + "GHSA-ghm9-cr32-g9qj"] = (200, bad)
        answer = {"results": [
            {"vulns": [{"id": "GHSA-ghm9-cr32-g9qj"}, {"id": HOSTILE}, {"id": "../../" + "x" * 80}]}, {}, {}]}
        report = m.run(LOCK, lambda u: fx.get(u, (404, None)), FakePost(answer))
        dumped = json.dumps(report) + m.render(report)
        self.assertNotIn("IGNORE", dumped)
        self.assertNotIn("evil", dumped)
        row = report["rows"][0]
        self.assertEqual((row["id"], row["status"], row["severity"], row["cves"], row["fixed"]),
                         ("GHSA-ghm9-cr32-g9qj", "GHSA_ONLY", "UNRECOGNIZED", [], []))
        self.assertEqual(len(report["rows"]), 1)

    def test_bad_ghsa_id_never_used_in_url(self):
        seen = []

        def get(url):
            seen.append(url)
            return 404, None

        answer = {"results": [{"vulns": [{"id": "GHSA-zzzz-zzzz-zzzz"}, {"id": "GHSA-ghm9-cr32-g9qj/../x"}]}, {}, {}]}
        report = m.run(LOCK, get, FakePost(answer))
        self.assertEqual(seen, [])
        self.assertEqual(report["rows"], [])


