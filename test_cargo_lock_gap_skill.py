def rec(vid, name, aliases, fixed, severity=None, refs=(), withdrawn=None, summary="x"):
    r = {
        "id": vid,
        "summary": summary,
        "details": summary,
        "aliases": list(aliases),
        "affected": [{"package": {"name": name, "ecosystem": "crates.io"},
                      "ranges": [{"type": "SEMVER", "events": [{"introduced": "0"}, {"fixed": fixed}]}]}],
        "references": [{"type": "WEB", "url": u} for u in refs],
    }
    if severity is not None:
        r["database_specific"] = {"severity": severity, "github_reviewed": True}
    if withdrawn is not None:
        r["withdrawn"] = withdrawn
    return r


